import { absoluteUrl, site } from "@/lib/site";

export type OpenGraphImage = {
  readonly url: string;
  readonly type?: string;
  readonly width?: number;
  readonly height?: number;
  readonly alt?: string;
};

export type OpenGraph = {
  readonly type: "website" | "article";
  readonly siteName: string;
  readonly locale: string;
  readonly url: string;
  readonly title: string;
  readonly description: string;
  readonly images: readonly OpenGraphImage[];
  readonly publishedTime?: string;
  readonly modifiedTime?: string;
};

export type TwitterCard = {
  readonly card: "summary_large_image";
  readonly title: string;
  readonly description: string;
  readonly images: readonly string[];
};

/** The card generated by src/pages/opengraph-image.ts. */
export const SOCIAL_IMAGE = {
  url: absoluteUrl(site.social.ogImage),
  width: 1200,
  height: 630,
  alt: `${site.name}: ${site.tagline}`,
} as const satisfies OpenGraphImage;

/**
 * The card URL as the Next.js build published it on the not-found page,
 * cache-busting query included, so the URL social caches hold stays valid.
 */
export const HASHED_SOCIAL_IMAGE: OpenGraphImage = {
  ...SOCIAL_IMAGE,
  url: `${SOCIAL_IMAGE.url}?8d78be5fe1536762`,
  type: "image/png",
};

export function pageSocial({
  path,
  title,
  description,
}: {
  path: string;
  title: string;
  description: string;
}): { openGraph: OpenGraph; twitter: TwitterCard } {
  return {
    openGraph: {
      type: "website",
      siteName: site.name,
      locale: site.openGraphLocale,
      url: absoluteUrl(path),
      title,
      description,
      images: [SOCIAL_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [SOCIAL_IMAGE.url],
    },
  };
}
